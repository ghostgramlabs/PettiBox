package com.ghostgramlabs.pettibox.data.sync

import com.ghostgramlabs.pettibox.data.sync.SyncRecord.Companion.F_FAV
import com.ghostgramlabs.pettibox.data.sync.SyncRecord.Companion.F_NOTES
import com.ghostgramlabs.pettibox.data.sync.SyncRecord.Companion.F_OCR
import com.ghostgramlabs.pettibox.data.sync.SyncRecord.Companion.F_TITLE
import com.ghostgramlabs.pettibox.data.sync.SyncRecord.Companion.F_TRASH
import com.ghostgramlabs.pettibox.data.sync.SyncRecord.Companion.KIND_ITEM
import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Test
import java.io.File
import java.util.Random

/**
 * Golden cases shared with the Chrome extension (sync-spec/vectors/). The
 * Kotlin engine is the reference: this test checks it still produces every
 * case, and extension/test/vectors.test.js checks the JavaScript port
 * reproduces them exactly.
 *
 * Regenerate after an intentional rule change:
 *   ./gradlew testDebugUnitTest --tests "*SyncVectors*" -PwriteSyncVectors=true
 */
class SyncVectorsTest {

    private val file = File(System.getProperty("repoRoot") ?: "..", "sync-spec/vectors/cases.json")

    @Test fun `engine reproduces the shared golden cases`() {
        val generated = generate()
        if (System.getProperty("writeSyncVectors") == "true" || !file.exists()) {
            file.parentFile.mkdirs()
            file.writeText(generated.toString() + "\n")
        }
        val stored = JSONObject(file.readText())
        assertEquals(stored.getString("shard"), generated.getString("shard"))
        assertEquals(canonical(stored.getJSONObject("shards")), canonical(generated.getJSONObject("shards")))
        assertEquals(stored.getJSONArray("merge").length(), generated.getJSONArray("merge").length())
        for (key in listOf("merge", "diff", "fold")) {
            val a = stored.getJSONArray(key)
            val b = generated.getJSONArray(key)
            for (i in 0 until a.length()) {
                assertEquals("$key case $i", canonical(a.get(i)), canonical(b.get(i)))
            }
        }
    }

    private fun generate(): JSONObject {
        val rnd = Random(2026)
        val merges = JSONArray()
        repeat(250) {
            val a = randomRecord(rnd)
            val b = randomRecord(rnd)
            val m = merge(a, b)
            merges.put(
                JSONObject()
                    .put("a", SyncCodec.encode(a))
                    .put("b", SyncCodec.encode(b))
                    .put("merged", SyncCodec.encode(m))
                    .put("view", view(m))
            )
        }
        val diffs = JSONArray()
        repeat(200) {
            val meta = if (rnd.nextInt(5) == 0) null else randomRecord(rnd)
            val local = randomLocal(rnd, meta)
            val dot = Dot("Z", 5_000L + rnd.nextInt(100))
            val out = SyncDiff.apply(meta, local, dot)
            diffs.put(
                JSONObject()
                    .put("meta", meta?.let(SyncCodec::encode) ?: JSONObject.NULL)
                    .put("local", local?.let(::encodeLocal) ?: JSONObject.NULL)
                    .put("dot", JSONObject().put("d", dot.dev).put("t", dot.ts))
                    .put("result", out?.let(SyncCodec::encode) ?: JSONObject.NULL)
            )
        }
        // The same link saved on two devices, folded together.
        val folds = JSONArray()
        repeat(120) {
            val keep = randomLink(rnd, "k", "P", 100L + rnd.nextInt(50))
            val other = randomLink(rnd, "o", "C", 200L + rnd.nextInt(50))
            val dot = Dot(listOf("P", "C")[rnd.nextInt(2)], 1_000L + rnd.nextInt(100))
            val (k, o) = SyncDedupe.fold(keep, other, dot)
            folds.put(
                JSONObject()
                    .put("keep", SyncCodec.encode(keep)).put("other", SyncCodec.encode(other))
                    .put("dot", JSONObject().put("d", dot.dev).put("t", dot.ts))
                    .put("kept", SyncCodec.encode(k)).put("removed", SyncCodec.encode(o))
            )
        }

        // A whole device file as the app writes it, for the extension to read.
        val shardRecords = (0 until 5).map { SyncCodec.decode(merges.getJSONObject(it).getJSONObject("merged")) }
            .mapIndexed { i, r -> r.copy(id = "s$i") }
        return JSONObject()
            .put("about", "Generated by SyncVectorsTest.kt from the Kotlin engine. Do not edit by hand.")
            .put("merge", merges)
            .put("diff", diffs)
            .put("fold", folds)
            .put("shard", SyncCodec.encodeShard("0123456789abcdef", "Pixel 8", 3, 1_760_000_000_000L, shardRecords))
            .put("shards", JSONObject().apply {
                for (id in listOf("books", "user_ab12cd34", "3f9c1e77a24b4d0e8b6a5c2f10d4e881", "ünïcødé", "", "0")) put(id, shardOf(id))
            })
    }

    /** A device file the Chrome extension wrote (extension/test/crossdevice.test.js keeps it in step). */
    @Test fun `the app reads a device file the extension wrote`() {
        val text = File(System.getProperty("repoRoot") ?: "..", "sync-spec/vectors/from-extension.json").readText().trim()
        val shard = SyncCodec.decodeShard(text, now = 1_760_000_000_100L)!!
        assertEquals("fedcba9876543210", shard.device)
        assertEquals("Chrome on laptop", shard.name)
        val col = shard.records.single { it.kind == SyncRecord.KIND_COLLECTION }
        assertEquals("From Chrome", col.value(SyncRecord.F_NAME))
        assertEquals(7L, col.value(SyncRecord.F_ORDER))
        val saved = shard.records.single { it.id.startsWith("0a") }
        assertEquals("Saved in Chrome", saved.value(F_TITLE))
        assertEquals("with a note", saved.value(F_NOTES))
        assertEquals("CHROME", saved.value(SyncRecord.F_SRC))
        assertEquals(mapOf("reading" to "Reading"), saved.presentTags())
        assertEquals("Ünïcødé title ✓", shard.records.single { it.id.startsWith("0b") }.value(F_TITLE))
        // Re-encoding gives the same file, so nothing is lost passing through the app.
        assertEquals(canonical(JSONObject(text)), canonical(JSONObject(SyncCodec.encodeShard(shard.device, shard.name, shard.shard, shard.generated, shard.records))))
    }

    /** What a phone would show for a record. */
    private fun view(r: SyncRecord): JSONObject = JSONObject()
        .put("gone", r.isGone)
        .put("trashed", r.isTrashed)
        .put("trashedAt", r.trashedAt ?: JSONObject.NULL)
        .put("title", r.value(F_TITLE) ?: JSONObject.NULL)
        .put("notes", r.value(F_NOTES) ?: JSONObject.NULL)
        .put("conflict", r.hasConflict)
        .put("tags", JSONObject(r.presentTags()))
        .put("files", JSONArray(r.presentFiles().keys.sorted()))

    private fun encodeLocal(l: LocalRecord): JSONObject = JSONObject()
        .put("k", l.kind).put("id", l.id).put("c", l.created)
        .put("f", JSONObject().apply { for ((k, v) in l.fields) put(k, v ?: JSONObject.NULL) })
        .put("tags", JSONObject(l.tags))
        .put("att", JSONObject().apply {
            for ((sha, ko) in l.files) put(sha, JSONObject().put("k", ko.first).put("o", ko.second))
        })

    private fun randomLocal(rnd: Random, meta: SyncRecord?): LocalRecord? {
        if (rnd.nextInt(6) == 0) return null
        val fields = mapOf(
            F_TITLE to (meta?.value(F_TITLE).takeIf { rnd.nextBoolean() } ?: "t${rnd.nextInt(4)}"),
            F_NOTES to (if (rnd.nextBoolean()) null else "n${rnd.nextInt(3)}"),
            F_FAV to rnd.nextBoolean(),
            F_OCR to (if (rnd.nextBoolean()) null else "o${rnd.nextInt(2)}"),
            F_TRASH to (if (rnd.nextInt(4) == 0) 4_000L + rnd.nextInt(50) else null)
        )
        val tags = listOf("Red", "Blue", "Green").filter { rnd.nextBoolean() }.associateBy { it.lowercase() }
        val files = listOf("aa", "bb").filter { rnd.nextBoolean() }.associateWith { "IMAGE" to rnd.nextInt(2).toLong() }
        return LocalRecord(KIND_ITEM, "s1", 1L, fields, tags, files)
    }

    /** A link save with a random mix of what folding looks at. */
    private fun randomLink(rnd: Random, id: String, dev: String, ts: Long): SyncRecord {
        val trash = if (rnd.nextInt(4) == 0) ts else null
        var r = SyncDiff.apply(
            null,
            LocalRecord(
                KIND_ITEM, id, ts,
                mapOf(
                    F_TITLE to listOf("Title", "https://e.com/x", "Other title")[rnd.nextInt(3)],
                    SyncRecord.F_URL to "https://e.com/x",
                    F_NOTES to listOf(null, "a", "ab", "note")[rnd.nextInt(4)],
                    SyncRecord.F_CAT to listOf(null, "c1", "c2")[rnd.nextInt(3)],
                    F_FAV to rnd.nextBoolean(),
                    SyncRecord.F_PIN to rnd.nextBoolean(),
                    SyncRecord.F_ARCH to rnd.nextBoolean(),
                    SyncRecord.F_REMIND to listOf(null, 5_000L)[rnd.nextInt(2)],
                    SyncRecord.F_THUMB to listOf(null, "t1")[rnd.nextInt(2)],
                    SyncRecord.F_TYPE to "LINK",
                    F_TRASH to trash
                ),
                listOf("Red", "Blue").filter { rnd.nextBoolean() }.associateBy { it.lowercase() },
                listOf("aa", "bb").filter { rnd.nextBoolean() }.withIndex().associate { (i, sha) -> sha to ("IMAGE" to i.toLong()) }
            ),
            Dot(dev, ts)
        )!!
        if (rnd.nextBoolean()) r = SyncWrite.field(r, SyncRecord.FILE_OCR_PREFIX + "aa", "words", Dot(dev, ts + 1))
        return r
    }

    private fun randomRecord(rnd: Random): SyncRecord {
        val devs = listOf("A", "B", "C")
        var r = SyncDiff.apply(
            null,
            LocalRecord(KIND_ITEM, "s1", 1L, mapOf(F_TITLE to "t0", F_NOTES to null, F_FAV to false, F_TRASH to null)),
            Dot("A", 1)
        )!!
        repeat(rnd.nextInt(7)) { i ->
            val dot = Dot(devs[rnd.nextInt(3)], 10L + rnd.nextInt(40) * 7 + i)
            r = when (rnd.nextInt(9)) {
                0 -> SyncWrite.field(r, F_TITLE, "t${rnd.nextInt(4)}", dot)
                1 -> SyncWrite.field(r, F_NOTES, if (rnd.nextBoolean()) null else "n${rnd.nextInt(3)}", dot)
                2 -> listOf("Red", "Blue")[rnd.nextInt(2)].let { SyncWrite.addTag(r, it.lowercase(), it, dot) }
                3 -> SyncWrite.removeTag(r, listOf("red", "blue")[rnd.nextInt(2)], dot)
                4 -> SyncWrite.trash(r, if (rnd.nextBoolean()) dot.ts else null, dot)
                5 -> SyncWrite.gone(r, dot)
                6 -> SyncWrite.addFile(r, listOf("aa", "bb")[rnd.nextInt(2)], "IMAGE", rnd.nextInt(2).toLong(), dot)
                7 -> SyncWrite.removeFile(r, listOf("aa", "bb")[rnd.nextInt(2)], dot)
                else -> SyncWrite.field(r, F_OCR, "o${rnd.nextInt(2)}", dot)
            }
        }
        return r
    }

    /** Key-sorted JSON text, so two equal values compare equal whatever their key order. */
    private fun canonical(v: Any?): String = when (v) {
        is JSONObject -> v.keys().asSequence().sorted().joinToString(",", "{", "}") { "\"$it\":" + canonical(v.get(it)) }
        is JSONArray -> (0 until v.length()).joinToString(",", "[", "]") { canonical(v.get(it)) }
        is String -> JSONObject.quote(v)
        JSONObject.NULL, null -> "null"
        is Number -> v.toLong().toString()
        else -> v.toString()
    }
}
